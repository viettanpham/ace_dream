/**
 * Initializes a new FleetPersonnelState
 */
export function createFleetPersonnelState(params: {
  fleetId: string
  homeBaseId: string
  residentBaseId?: string
  initialMorale?: number
  gameDay?: number
}): FleetPersonnelState {
  return {
    fleetId: params.fleetId,
    crewPool: {
      fleetId: params.fleetId,
      homeBaseId: params.homeBaseId,
      residentBaseId: params.residentBaseId || params.homeBaseId,
      crewIdle: 0,
      crewAssigned: 0,
      crewReserve: 0,
      totalCrew: 0,
    },
    assignedPilots: {},
    morale: params.initialMorale ?? 85,
    lastPayrollDay: params.gameDay ?? 1,
    casualtyHistory: [],
  }
}

/**
 * Appoints a Named Pilot as Fleet Captain (Thuyền Trưởng Hạm Đội)
 */
export function appointFleetCaptain(
  state: FleetPersonnelState,
  pilot: NamedPilotRef
): { success: boolean; previousCaptain?: NamedPilotRef } {
  const previousCaptain = state.captain
  pilot.assignedFleetId = state.fleetId
  pilot.currentRole = "CAPTAIN"
  pilot.status = "ACTIVE_DUTY"
  state.captain = pilot
  state.assignedPilots[pilot.pilotId] = pilot
  return { success: true, previousCaptain }
}

/**
 * Relieves the current Fleet Captain
 */
export function relieveFleetCaptain(
  state: FleetPersonnelState
): { success: boolean; relievedCaptain?: NamedPilotRef } {
  const relievedCaptain = state.captain
  if (!relievedCaptain) {
    return { success: false }
  }
  relievedCaptain.currentRole = undefined
  relievedCaptain.status = "SHORE_LEAVE"
  state.captain = undefined
  return { success: true, relievedCaptain }
}

