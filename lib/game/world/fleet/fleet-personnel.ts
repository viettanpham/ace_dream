/**
 * STARFRONT WORLD — Hybrid Workforce, Academy & Crew Pool Engine (Phase 7.3)
 *
 * Implements:
 * 1. Hybrid Workforce Dual-Track Architecture:
 *    - Track A: Named Pilots & Mech Commanders (Character V1 / Pilot Survival)
 *      Individually addressable leaders (Captain, XO, Wing Commander). Never workforce counters.
 *    - Track B: Operational Fleet Crew Pool (FleetCrewPool from FND-4)
 *      Quantified collective workforce (idle, assigned, reserve, casualties).
 * 2. 3-Pass Ship Crew Allocator:
 *    - Pass 1: MINIMUM Staffing (crucial operational viability, canOperate = true)
 *    - Pass 2: TARGET Staffing (100% optimal combat performance)
 *    - Pass 3: MAXIMUM Buff Staffing (125% turnaround & repair boost)
 * 3. Base Naval Academy (NAVAL_ACADEMY) Training Engine:
 *    - Recruits from Base RESIDENT population into training cohorts
 *    - Time-gated completion across Game Days with resource upkeep
 *    - Population conservation invariant: Base available decreases strictly by recruited headcount
 * 4. Realistic In-Transit Personnel Transfers (No Teleportation Invariant):
 *    - Movement lag determined by Hyperlane network distance
 *    - Zero-sum headcount tracking across Base, In-Transit, and Fleet pools
 * 5. Battle Casualties & Fleet Discharge:
 *    - Casualty tracking and morale impact
 *    - Formal discharge back to Base available population
 */

