/**
 * Relieves the Captain of an individual Ship
 */
export function relieveShipCaptain(
  state: FleetPersonnelState,
  ship: ShipInstance
): { success: boolean; relievedPilot?: NamedPilotRef } {
  const pilotId = ship.assignedPilotId
  if (!pilotId) {
    return { success: false }
  }
  const relievedPilot = state.assignedPilots[pilotId]
  if (relievedPilot) {
    relievedPilot.assignedShipId = undefined
    relievedPilot.currentRole = undefined
    relievedPilot.status = "SHORE_LEAVE"
  }
  ship.assignedPilotId = undefined
  return { success: true, relievedPilot }
}

/**
 * Assigns a Named Pilot to Temporary Detached Duty (Biệt phái tạm thời sang hạm đội/căn cứ khác)
 */
export function assignPilotDetachedDuty(
  pilot: NamedPilotRef,
  params: {
    targetFleetId?: string
    targetBaseId?: string
    durationDays: number
    gameDay: number
    reason: string
  }
): { success: boolean; returnGameDay: number } {
  const returnGameDay = params.gameDay + Math.max(1, params.durationDays)
  pilot.status = "DETACHED_DUTY"
  pilot.detachedDuty = {
    targetFleetId: params.targetFleetId,
    targetBaseId: params.targetBaseId,
    startedGameDay: params.gameDay,
    durationDays: params.durationDays,
    returnGameDay,
    reason: params.reason,
  }
  return { success: true, returnGameDay }
}

/**
 * Processes return of pilots from Temporary Detached Duty when duration expires
 */
export function processDetachedDutyReturns(
  pilots: NamedPilotRef[],
  currentGameDay: number
): { returnedPilots: NamedPilotRef[]; remainingDetached: number } {
  const returnedPilots: NamedPilotRef[] = []
  let remainingDetached = 0

  for (const pilot of pilots) {
    if (pilot.status === "DETACHED_DUTY" && pilot.detachedDuty) {
      if (currentGameDay >= pilot.detachedDuty.returnGameDay) {
        pilot.status = "ACTIVE_DUTY"
        pilot.detachedDuty = undefined
        returnedPilots.push(pilot)
      } else {
        remainingDetached++
      }
    }
  }

  return { returnedPilots, remainingDetached }
}

/**
 * Executes 3-Pass Workforce Allocation on all ships within a Fleet:
 *
 * Pass 1: MINIMUM Staffing
 *   - Ensures every operational ship reaches its minimumCrew threshold
 *   - Prioritizes flagship and combat capital vessels first
 *   - Ships receiving less than minimumCrew are flagged canOperate = false
 *
 * Pass 2: TARGET Staffing
 *   - Allocates remaining idle crew up to targetCrew (100% optimal performance)
 *
 * Pass 3: MAXIMUM Buff Staffing
 *   - Distributes any surplus idle crew up to maximumCrew for priority ships
 *   - Grants efficiency = 1.25 (+25% turnaround & battle repair boost)
 */
export function allocateFleetCrewToShips(
  crewPool: FleetCrewPool,
  ships: ShipInstance[],
  options?: {
    prioritizeFlagshipId?: string
  }
): FleetCrewAllocationReport {
  const diagnostics: string[] = []
  const idleBefore = crewPool.crewIdle
  const totalBefore = crewPool.totalCrew

  // Return all currently assigned crew to idle pool before performing full fresh allocation
  let availableCrew = crewPool.crewIdle + crewPool.crewAssigned
  crewPool.crewIdle = availableCrew
  crewPool.crewAssigned = 0

  // Filter ships that require crew and sort by strategic priority
  // Priority: 1. Flagship (100), 2. Carrier/Battleship (80), 3. Cruiser/Frigate (60), 4. Corvette/Logistics (40)
  const sortedShips = [...ships].sort((a, b) => {
    if (options?.prioritizeFlagshipId) {
      if (a.instanceId === options.prioritizeFlagshipId) return -1
      if (b.instanceId === options.prioritizeFlagshipId) return 1
    }
    return b.maxHullHp - a.maxHullHp // Larger tonnage receives higher initial priority
  })

  // Initialize tracking allocations
  const allocations: Record<string, ShipCrewAllocationDetail> = {}
  for (const ship of sortedShips) {
    const status = evaluateShipCrewStatus(ship)
    allocations[ship.instanceId] = {
      shipId: ship.instanceId,
      shipName: ship.customName || ship.serialNumber,
      assignedCount: 0,
      pass1Assigned: 0,
      pass2Assigned: 0,
      pass3Assigned: 0,
      minimumCrew: status.minimumCrew,
      targetCrew: status.targetCrew,
      maximumCrew: status.maximumCrew,
      efficiency: 0.4,
      canOperate: false,
      isUnderStaffed: true,
    }
  }

  let pass1Total = 0
  let pass2Total = 0
  let pass3Total = 0

  // === PASS 1: MINIMUM STAFFING ===
  for (const ship of sortedShips) {
    if (availableCrew <= 0) break
    const alloc = allocations[ship.instanceId]
    const needed = alloc.minimumCrew
    const toAssign = Math.min(availableCrew, needed)

    alloc.pass1Assigned = toAssign
    alloc.assignedCount += toAssign
    availableCrew -= toAssign
    pass1Total += toAssign

    if (alloc.assignedCount < alloc.minimumCrew) {
      diagnostics.push(`Ship ${alloc.shipName} received under minimum crew (${alloc.assignedCount}/${alloc.minimumCrew}).`)
    }
  }

  // === PASS 2: TARGET STAFFING ===
  if (availableCrew > 0) {
    for (const ship of sortedShips) {
      if (availableCrew <= 0) break
      const alloc = allocations[ship.instanceId]
      // Only advance ships that achieved minimum in Pass 1
      if (alloc.assignedCount >= alloc.minimumCrew) {
        const deltaToTarget = alloc.targetCrew - alloc.assignedCount
        if (deltaToTarget > 0) {
          const toAssign = Math.min(availableCrew, deltaToTarget)
          alloc.pass2Assigned = toAssign
          alloc.assignedCount += toAssign
          availableCrew -= toAssign
          pass2Total += toAssign
        }
      }
    }
  }

  // === PASS 3: MAXIMUM BUFF STAFFING ===
  if (availableCrew > 0) {
    for (const ship of sortedShips) {
      if (availableCrew <= 0) break
      const alloc = allocations[ship.instanceId]
      // Only buff ships that achieved full target
      if (alloc.assignedCount >= alloc.targetCrew) {
        const deltaToMax = alloc.maximumCrew - alloc.assignedCount
        if (deltaToMax > 0) {
          const toAssign = Math.min(availableCrew, deltaToMax)
          alloc.pass3Assigned = toAssign
          alloc.assignedCount += toAssign
          availableCrew -= toAssign
          pass3Total += toAssign
        }
      }
    }
  }

  // Update crew pool balances
  const totalAssigned = pass1Total + pass2Total + pass3Total
  crewPool.crewAssigned = totalAssigned
  crewPool.crewIdle = availableCrew
  crewPool.totalCrew = crewPool.crewIdle + crewPool.crewAssigned + crewPool.crewReserve

  // Apply assignments directly back to ship instances and update their runtime statuses
  let operationalCount = 0
  let understaffedCount = 0
  let buffedCount = 0

  for (const ship of sortedShips) {
    const alloc = allocations[ship.instanceId]
    ship.assignedCrewCount = alloc.assignedCount

    // Evaluate operational status with newly assigned crew count
    const status = evaluateShipCrewStatus(ship)
    alloc.efficiency = status.efficiency
    alloc.canOperate = status.canOperate
    alloc.isUnderStaffed = status.isUnderStaffed

    if (status.canOperate) operationalCount++
    if (status.isUnderStaffed) understaffedCount++
    if (status.efficiency >= 1.25) buffedCount++
  }

  return {
    fleetId: crewPool.fleetId,
    totalCrewBefore: totalBefore,
    idleCrewBefore: idleBefore,
    idleCrewAfter: crewPool.crewIdle,
    totalAssigned,
    pass1Total,
    pass2Total,
    pass3Total,
    shipsEvaluated: sortedShips.length,
    operationalShipsCount: operationalCount,
    understaffedShipsCount: understaffedCount,
    buffedShipsCount: buffedCount,
    shipAllocations: allocations,
    diagnostics,
  }
}

/**
 * Initiates training of new naval crew at Base Naval Academy
 *
 * Invariant: Base available population decreases by traineeCount. Zero teleportation/creation.
 */
export function startNavalAcademyTraining(params: {
  baseState: BasePopulationState
  baseResources?: {
    credits?: number
    food?: number
    logisticsSupplies?: number
  }
  traineeCount: number
  gameDay: number
  targetFleetId?: string
  durationDays?: number
}): {
  success: boolean
  reason?: string
  batch?: AcademyTrainingBatch
} {
  const { baseState, baseResources, traineeCount, gameDay, targetFleetId } = params
  const duration = params.durationDays ?? 14

  if (traineeCount <= 0) {
    return { success: false, reason: "Trainee count must be greater than 0." }
  }

  if (baseState.populationAvailable < traineeCount) {
    return {
      success: false,
      reason: `INSUFFICIENT_AVAILABLE_POPULATION: Base has ${baseState.populationAvailable}, required ${traineeCount}.`,
    }
  }

  // Cost formulas: 10 credits, 2 food, 1 supplies per trainee
  const cost = {
    credits: traineeCount * 10,
    food: traineeCount * 2,
    logisticsSupplies: traineeCount * 1,
  }

  if (baseResources) {
    if ((baseResources.credits ?? Infinity) < cost.credits) {
      return { success: false, reason: "Insufficient credits for academy tuition and training materials." }
    }
    if ((baseResources.food ?? Infinity) < cost.food) {
      return { success: false, reason: "Insufficient food rations for academy cadets." }
    }
    if ((baseResources.logisticsSupplies ?? Infinity) < cost.logisticsSupplies) {
      return { success: false, reason: "Insufficient supplies for training equipment." }
    }
    baseResources.credits = (baseResources.credits ?? cost.credits) - cost.credits
    baseResources.food = (baseResources.food ?? cost.food) - cost.food
    baseResources.logisticsSupplies = (baseResources.logisticsSupplies ?? cost.logisticsSupplies) - cost.logisticsSupplies
  }

  // Deduct from Base Available and record in Base Occupied (category: FLEET_CREW)
  baseState.populationAvailable -= traineeCount
  baseState.populationOccupied += traineeCount
  baseState.breakdown.FLEET_CREW = (baseState.breakdown.FLEET_CREW || 0) + traineeCount

  const batch: AcademyTrainingBatch = {
    batchId: `academy_batch_${baseState.baseId}_${gameDay}_${Math.random().toString(36).slice(2, 6)}`,
    baseId: baseState.baseId,
    traineeCount,
    startedGameDay: gameDay,
    completionGameDay: gameDay + duration,
    durationDays: duration,
    targetFleetId,
    costPaid: cost,
    status: "TRAINING",
  }

  return { success: true, batch }
}

/**
 * Settles completed training batches at Naval Academy across game days
 */
export function processNavalAcademyGraduation(
  batches: AcademyTrainingBatch[],
  currentGameDay: number,
  destinationPool?: FleetCrewPool
): {
  graduatedBatches: AcademyTrainingBatch[]
  totalGraduatedCount: number
  remainingTrainingCount: number
} {
  const graduatedBatches: AcademyTrainingBatch[] = []
  let totalGraduatedCount = 0
  let remainingTrainingCount = 0

  for (const batch of batches) {
    if (batch.status === "TRAINING") {
      if (currentGameDay >= batch.completionGameDay) {
        batch.status = "COMPLETED"
        graduatedBatches.push(batch)
        totalGraduatedCount += batch.traineeCount

        // If a destination pool is present on-site, directly integrate into fleet idle pool
        if (destinationPool && (!batch.targetFleetId || destinationPool.fleetId === batch.targetFleetId)) {
          destinationPool.crewIdle += batch.traineeCount
          destinationPool.totalCrew = destinationPool.crewIdle + destinationPool.crewAssigned + destinationPool.crewReserve
        }
      } else {
        remainingTrainingCount += batch.traineeCount
      }
    }
  }

  return { graduatedBatches, totalGraduatedCount, remainingTrainingCount }
}

/**
 * Dispatches a realistic personnel transfer record across the Hyperlane network
 *
 * Invariant: No Instant Teleportation. Movement requires travel days based on route hops.
 */
export function dispatchPersonnelTransfer(params: {
  sourceBaseId: string
  destinationFleetId?: string
  destinationBaseId: string
  headcount: number
  departureGameDay: number
  hyperlaneHops: number
  sourcePool?: FleetCrewPool
  baseState?: BasePopulationState
  reason: string
}): {
  success: boolean
  reason?: string
  transfer?: PopulationTransferRecord
} {
  const {
    sourceBaseId,
    destinationFleetId,
    destinationBaseId,
    headcount,
    departureGameDay,
    hyperlaneHops,
    sourcePool,
    baseState,
    reason,
  } = params

  if (headcount <= 0) {
    return { success: false, reason: "Headcount must be positive." }
  }

  // Deduct from source pool if transferring from an existing fleet
  if (sourcePool) {
    if (sourcePool.crewIdle < headcount) {
      return { success: false, reason: "Insufficient idle crew in source fleet pool." }
    }
    sourcePool.crewIdle -= headcount
    sourcePool.totalCrew = sourcePool.crewIdle + sourcePool.crewAssigned + sourcePool.crewReserve
  } else if (baseState) {
    // If transferring directly from Base available population
    if (baseState.populationAvailable < headcount) {
      return { success: false, reason: "Insufficient available population at source base." }
    }
    baseState.populationAvailable -= headcount
    baseState.populationOccupied += headcount
    baseState.breakdown.FLEET_CREW = (baseState.breakdown.FLEET_CREW || 0) + headcount
  }

  // 1 hop = 1 day minimum travel duration
  const travelDays = Math.max(1, hyperlaneHops)
  const transfer: PopulationTransferRecord = {
    transferId: `trans_crew_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
    sourceBaseId,
    destinationBaseId,
    headcount,
    category: "RESIDENT",
    startedGameDay: departureGameDay,
    estimatedArrivalGameDay: departureGameDay + travelDays,
    status: "IN_TRANSIT",
    reason,
    metadata: {
      destinationFleetId,
      personnelType: "FLEET_CREW",
      hyperlaneHops,
    },
  }

  return { success: true, transfer }
}

/**
 * Settles arriving personnel transfers at their target fleet or base
 */
export function processPersonnelArrival(
  transfers: PopulationTransferRecord[],
  currentGameDay: number,
  targetPool: FleetCrewPool
): {
  arrivedCount: number
  processedTransfers: PopulationTransferRecord[]
} {
  let arrivedCount = 0
  const processedTransfers: PopulationTransferRecord[] = []

  for (const transfer of transfers) {
    if (transfer.status === "IN_TRANSIT" && currentGameDay >= transfer.estimatedArrivalGameDay) {
      const targetFleetId = transfer.metadata?.destinationFleetId
      if (!targetFleetId || targetFleetId === targetPool.fleetId) {
        transfer.status = "COMPLETED"
        transfer.actualArrivalGameDay = currentGameDay
        targetPool.crewIdle += transfer.headcount
        targetPool.totalCrew = targetPool.crewIdle + targetPool.crewAssigned + targetPool.crewReserve
        arrivedCount += transfer.headcount
        processedTransfers.push(transfer)
      }
    }
  }

  return { arrivedCount, processedTransfers }
}

/**
 * Applies battle casualties to a fleet's crew pool and affected ships
 */
export function applyFleetBattleCasualties(
  personnelState: FleetPersonnelState,
  ships: ShipInstance[],
  totalCasualties: number,
  gameDay: number,
  cause = "Hostile fleet engagement"
): {
  actualCasualtiesApplied: number
  newTotalCrew: number
  moraleDelta: number
} {
  const pool = personnelState.crewPool
  if (totalCasualties <= 0 || pool.crewAssigned <= 0) {
    return { actualCasualtiesApplied: 0, newTotalCrew: pool.totalCrew, moraleDelta: 0 }
  }

  const casualties = Math.min(totalCasualties, pool.crewAssigned)
  pool.crewAssigned -= casualties
  pool.totalCrew = pool.crewIdle + pool.crewAssigned + pool.crewReserve

  // Distribute casualties pro-rata across damaged ships
  let remainingCasualties = casualties
  for (const ship of ships) {
    if (remainingCasualties <= 0) break
    if (ship.assignedCrewCount > 0 && ship.hullHp < ship.maxHullHp) {
      const shipCasualties = Math.min(
        ship.assignedCrewCount,
        Math.ceil(remainingCasualties * 0.5)
      )
      ship.assignedCrewCount -= shipCasualties
      remainingCasualties -= shipCasualties
      evaluateShipCrewStatus(ship)
    }
  }

  // Morale impact (-1% per 10 casualties, clamped [10..100])
  const moralePenalty = Math.min(25, Math.ceil(casualties / 10))
  personnelState.morale = Math.max(10, personnelState.morale - moralePenalty)

  personnelState.casualtyHistory.push({
    gameDay,
    count: casualties,
    cause,
  })

  return {
    actualCasualtiesApplied: casualties,
    newTotalCrew: pool.totalCrew,
    moraleDelta: -moralePenalty,
  }
}

/**
 * Formally discharges crew members from a Fleet back into Base available population
 * Invariant: Fleet/Guild owns its crew; discharge is an explicit authorized transfer.
 */
export function dischargeCrewToBase(
  fleetPool: FleetCrewPool,
  baseState: BasePopulationState,
  count: number
): { success: boolean; dischargedCount: number; reason?: string } {
  if (count <= 0) {
    return { success: true, dischargedCount: 0 }
  }

  if (fleetPool.crewIdle < count) {
    return {
      success: false,
      dischargedCount: 0,
      reason: `INSUFFICIENT_IDLE_CREW: Fleet has ${fleetPool.crewIdle} idle crew, requested discharge of ${count}.`,
    }
  }

  // Remove from Fleet Idle pool
  fleetPool.crewIdle -= count
  fleetPool.totalCrew = fleetPool.crewIdle + fleetPool.crewAssigned + fleetPool.crewReserve

  // Return to Base Available population and reduce FLEET_CREW occupied count
  baseState.populationAvailable += count
  baseState.populationOccupied = Math.max(0, baseState.populationOccupied - count)
  if (baseState.breakdown.FLEET_CREW) {
    baseState.breakdown.FLEET_CREW = Math.max(0, baseState.breakdown.FLEET_CREW - count)
  }

  return { success: true, dischargedCount: count }
}
